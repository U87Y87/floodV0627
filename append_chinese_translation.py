    for j, line in enumerate(text.split("\n")):
        if j:
            p.add_run().add_break()
        run = p.add_run(line)
        run.font.name = "Microsoft YaHei"
        run._element.rPr.rFonts.set("{http://schemas.openxmlformats.org/wordprocessingml/2006/main}eastAsia", "Microsoft YaHei")
